#!/usr/bin/env python3
"""Fetches Lucide icons (ISC licence) and converts them to Android vector drawables.

Usage: Tools/lucide-to-vector.py <name>... --out Android/app/src/main/res/drawable
Each icon becomes ic_<name with - replaced by _>.xml with a 1.5 px round monoline stroke.
"""
import argparse
import re
import sys
import urllib.request
import xml.etree.ElementTree as ET

BASE = "https://raw.githubusercontent.com/lucide-icons/lucide/main/icons/{}.svg"
NS = "{http://www.w3.org/2000/svg}"


def num(v, default=0.0):
    return float(v) if v is not None else default


def fmt(v):
    s = ("%.3f" % v).rstrip("0").rstrip(".")
    return s if s not in ("-0", "") else "0"


def circle(cx, cy, rx, ry):
    return (f"M{fmt(cx - rx)},{fmt(cy)}a{fmt(rx)},{fmt(ry)} 0 1,0 {fmt(2 * rx)},0"
            f"a{fmt(rx)},{fmt(ry)} 0 1,0 {fmt(-2 * rx)},0")


def rect(x, y, w, h, rx, ry):
    if rx <= 0 and ry <= 0:
        return f"M{fmt(x)},{fmt(y)}h{fmt(w)}v{fmt(h)}h{fmt(-w)}z"
    rx = rx or ry
    ry = ry or rx
    rx, ry = min(rx, w / 2), min(ry, h / 2)
    return (f"M{fmt(x + rx)},{fmt(y)}h{fmt(w - 2 * rx)}a{fmt(rx)},{fmt(ry)} 0 0,1 {fmt(rx)},{fmt(ry)}"
            f"v{fmt(h - 2 * ry)}a{fmt(rx)},{fmt(ry)} 0 0,1 {fmt(-rx)},{fmt(ry)}"
            f"h{fmt(-(w - 2 * rx))}a{fmt(rx)},{fmt(ry)} 0 0,1 {fmt(-rx)},{fmt(-ry)}"
            f"v{fmt(-(h - 2 * ry))}a{fmt(rx)},{fmt(ry)} 0 0,1 {fmt(rx)},{fmt(-ry)}z")


def points(s, close):
    nums = [float(n) for n in re.split(r"[\s,]+", s.strip()) if n]
    pts = list(zip(nums[0::2], nums[1::2]))
    d = "M" + " L".join(f"{fmt(x)},{fmt(y)}" for x, y in pts)
    return d + ("z" if close else "")


def to_paths(svg_text):
    root = ET.fromstring(svg_text)
    out = []
    for el in root.iter():
        tag = el.tag.replace(NS, "")
        a = el.attrib
        if tag == "path":
            out.append(a["d"])
        elif tag == "circle":
            out.append(circle(num(a.get("cx")), num(a.get("cy")), num(a.get("r")), num(a.get("r"))))
        elif tag == "ellipse":
            out.append(circle(num(a.get("cx")), num(a.get("cy")), num(a.get("rx")), num(a.get("ry"))))
        elif tag == "rect":
            out.append(rect(num(a.get("x")), num(a.get("y")), num(a.get("width")), num(a.get("height")),
                            num(a.get("rx")), num(a.get("ry"))))
        elif tag == "line":
            out.append(f"M{fmt(num(a.get('x1')))},{fmt(num(a.get('y1')))}L{fmt(num(a.get('x2')))},{fmt(num(a.get('y2')))}")
        elif tag in ("polyline", "polygon"):
            out.append(points(a["points"], tag == "polygon"))
    return out


def vector(paths):
    body = "\n".join(
        f'    <path android:pathData="{p}" android:strokeColor="#FFFFFFFF" android:strokeWidth="1.5" '
        f'android:strokeLineCap="round" android:strokeLineJoin="round" android:fillColor="#00000000"/>'
        for p in paths)
    return ('<?xml version="1.0" encoding="utf-8"?>\n'
            '<!-- Lucide (ISC) — generated by Tools/lucide-to-vector.py -->\n'
            '<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="24dp" android:height="24dp" '
            'android:viewportWidth="24" android:viewportHeight="24">\n' + body + "\n</vector>\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("names", nargs="+")
    ap.add_argument("--out", required=True)
    args = ap.parse_args()
    failed = []
    for name in args.names:
        try:
            svg = urllib.request.urlopen(BASE.format(name), timeout=20).read().decode()
            with open(f"{args.out}/ic_{name.replace('-', '_')}.xml", "w") as f:
                f.write(vector(to_paths(svg)))
        except Exception as e:  # noqa: BLE001 - report and continue
            failed.append(f"{name}: {e}")
    if failed:
        print("\n".join(failed), file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()
