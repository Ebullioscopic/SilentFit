// Regenerates js/presets.js from the app's own presets.
//   cd Android && SILENTFIT_EXPORT_PRESETS=/tmp/presets.json gradle :app:testDebugUnitTest --tests '*ExportPresetsTest*'
//   node website/tools/make-presets.js /tmp/presets.json > website/js/presets.js
const fs = require('fs');
const src = JSON.parse(fs.readFileSync(process.argv[2], 'utf8'));
const out = {};
for (const [key, p] of Object.entries(src)) out[key] = { ...p.spec, category: p.category, description: p.description };
process.stdout.write(`/* GENERATED by tools/make-presets.js from Android Presets.kt — do not edit by hand. */
window.PRESETS = ${JSON.stringify(out, null, 1)};

window.DEFAULT_FACE = {
  format: 'silentfit.face',
  version: 1,
  name: 'Untitled',
  width: 240,
  height: 280,
  background: { color: '#000000' },
  elements: [],
  assets: {},
};
`);
